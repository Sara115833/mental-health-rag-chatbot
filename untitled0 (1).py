import requests
from bs4 import BeautifulSoup
import pandas as pd

# List of article URLs to scrape
urls = [
    "https://www.verywellmind.com/what-is-anxiety-2795454",
    "https://www.verywellmind.com/what-is-depression-2795029",
    "https://www.verywellmind.com/what-is-cognitive-behavioral-therapy-2795747",
    "https://www.verywellmind.com/tips-to-reduce-stress-3145195"
]

all_paragraphs = []

# Loop through URLs and extract paragraph texts
for url in urls:
    print(f"Scraping: {url}")
    try:
        response = requests.get(url, headers={"User-Agent": "Mozilla/5.0"})
        soup = BeautifulSoup(response.text, 'html.parser')
        paragraphs = soup.find_all('p')
        text_data = [p.get_text().strip() for p in paragraphs if len(p.get_text().strip()) > 30]
        all_paragraphs.extend(text_data)
    except Exception as e:
        print(f"Error scraping {url}: {e}")

# Save all extracted paragraphs to a CSV file
df = pd.DataFrame(all_paragraphs, columns=['paragraph'])
df.to_csv('mental_health_data.csv', index=False, encoding='utf-8')

print(f"✅ Done! Collected {len(all_paragraphs)} paragraphs.")

