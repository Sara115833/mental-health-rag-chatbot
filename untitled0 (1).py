import pandas as pd
import re

# Load the collected data
df = pd.read_csv("mental_health_data.csv")

# Combine all paragraphs into one long string
full_text = ' '.join(df['paragraph'].dropna().tolist())

# Clean the text (remove extra spaces, special symbols, etc.)
cleaned_text = re.sub(r'\s+', ' ', full_text)  # remove newlines, tabs, etc.
cleaned_text = re.sub(r'[^a-zA-Z0-9.,;:!?()\s]', '', cleaned_text)  # keep letters, numbers & punctuation

# Split into words
words = cleaned_text.split()

# Split into chunks of ~400 words
chunk_size = 400
chunks = []

for i in range(0, len(words), chunk_size):
    chunk = ' '.join(words[i:i+chunk_size])
    if len(chunk.split()) >= 200:  # make sure chunk has at least 200 words
        chunks.append(chunk)

# Save the chunks in a new CSV
chunk_df = pd.DataFrame(chunks, columns=["chunk"])
chunk_df.to_csv("cleaned_chunks.csv", index=False, encoding="utf-8")

print(f"✅ Done! Saved {len(chunks)} chunks.")

