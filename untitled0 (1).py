import faiss
import numpy as np
import pandas as pd
from sentence_transformers import SentenceTransformer
from transformers import AutoTokenizer, AutoModelForCausalLM
import torch

# Load FAISS index and chunks
index = faiss.read_index("faiss_index.index")
df_chunks = pd.read_csv("indexed_chunks.csv")

# Load embedding model
embed_model = SentenceTransformer('all-MiniLM-L6-v2')

# Load Hugging Face language model (DistilGPT2 or small model for demo)
tokenizer = AutoTokenizer.from_pretrained("distilgpt2")
model = AutoModelForCausalLM.from_pretrained("distilgpt2")

# Function to answer questions
def ask_question_rag(question, top_k=3):
    # Embed the question
    q_embedding = embed_model.encode([question])

    # Search in FAISS index
    D, I = index.search(q_embedding, top_k)

    # Get top matching chunks
    retrieved_chunks = df_chunks.iloc[I[0]]['chunk'].tolist()
    context = "\n\n".join(retrieved_chunks)

    # Create prompt
    prompt = f"""You are a mental health assistant. Use the following context to answer the user's question.

Context:
{context}

Question: {question}
Answer:"""

    # Tokenize input
    inputs = tokenizer.encode(prompt, return_tensors="pt", max_length=1024, truncation=True)

    # Generate response
    outputs = model.generate(inputs, max_new_tokens=150, do_sample=True, temperature=0.7)
    answer = tokenizer.decode(outputs[0], skip_special_tokens=True)

    return answer.split("Answer:")[-1].strip()

# Example usage
print(ask_question_rag("What is cognitive behavioral therapy?"))

